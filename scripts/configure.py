#!/usr/bin/env python3
"""Generate a runnable local config and infra/.env from the paper template.

The API key is never written into the YAML; only into the gitignored infra/.env
when explicitly passed with --api-key (or inherited from DEEPSEEK_API_KEY).
"""
from __future__ import annotations

import argparse
import json
import os
import secrets
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE_PAPER = ROOT / "configs" / "minecraft-paper-aligned.yaml"
TEMPLATE_LONGRUN = ROOT / "configs" / "minecraft-longrun.yaml"


def token() -> str:
    return secrets.token_hex(32)


def write_env(path: Path, *, api_key: str | None, accept_eula: bool) -> None:
    values = {
        "ACCEPT_EULA": "true" if accept_eula else "false",
        "MC_SEED": "42",
        "MC_SERVER_CONTAINER": "minecraft-paper-server",
        "HARNESS_PROJECT": "minecraft-paper",
        "GAME_CHAT": "true",
        "SERVER_DATA_DIR": "./server-data",
        "MC_UID": str(os.getuid()),
        "MC_GID": str(os.getgid()),
        "JAVA_IMAGE": "eclipse-temurin:17-jre-jammy",
        "NODE_IMAGE": "node:22-bookworm-slim",
    }
    for index in range(1, 17):
        values[f"WORKER{index}_TOKEN"] = token()
        values[f"BOT{index}_ADMIN_TOKEN"] = token()
        values[f"BOT{index}_AGENT_TOKENS_JSON"] = json.dumps({f"player{index}": token()}, separators=(",", ":"))
    if api_key:
        values["DEEPSEEK_API_KEY"] = api_key
    lines = ["# Generated by ./setup.sh. Do not commit this file."]
    for key, value in values.items():
        lines.append(f"{key}={value}")
    path.write_text("\n".join(lines) + "\n")
    path.chmod(0o600)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=ROOT / "configs" / "local.yaml")
    parser.add_argument("--name", default="minecraft-harness-local")
    parser.add_argument("--agents", type=int, choices=range(1, 17), default=4)
    parser.add_argument("--model", default="deepseek-flash")
    parser.add_argument("--base-url", default="https://api.deepseek.com")
    parser.add_argument("--api-key", default=os.environ.get("DEEPSEEK_API_KEY"))
    parser.add_argument("--wall-minutes", type=int, default=60)
    parser.add_argument("--max-calls", type=int, default=2000)
    parser.add_argument("--max-cost", type=float, default=5.0)
    parser.add_argument("--world", type=Path, default=ROOT / "infra" / "server-data" / "world")
    parser.add_argument("--log", type=Path, default=ROOT / "infra" / "server-data" / "logs" / "latest.log")
    parser.add_argument("--accept-eula", action="store_true")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()

    if not 1 <= args.agents <= 16:
        raise SystemExit("agents must be 1..16")
    if args.config.exists() and not args.force:
        print(f"config exists: {args.config}; use --force to replace", file=sys.stderr)
        return 2

    template = TEMPLATE_PAPER if args.agents == 4 else TEMPLATE_LONGRUN
    data = yaml.safe_load(template.read_text())
    data.setdefault("experiment", {})["name"] = args.name
    data["agents"]["count"] = args.agents
    data["agents"]["ids"] = [f"player{i + 1}" for i in range(args.agents)]
    model = data.setdefault("model", {})
    model.update(kind="chat_completions", base_url=args.base_url, model=args.model,
                 api_key_env="DEEPSEEK_API_KEY", max_retries=0,
                 extra_body={"thinking": {"type": "disabled"}})
    runtime = data.setdefault("runtime", {})
    runtime["urls"] = {f"player{i + 1}": f"http://127.0.0.1:{3101 + i}" for i in range(args.agents)}
    runtime["token_envs"] = {f"player{i + 1}": f"BOT{i + 1}_ADMIN_TOKEN" for i in range(args.agents)}
    server = data.setdefault("server", {})
    server["world_dir"] = str(args.world.resolve())
    server["log_path"] = str(args.log.resolve())
    server.setdefault("managed_container", "minecraft-paper-server")
    budgets = data.setdefault("budgets", {})
    budgets.update(wall_time_minutes=args.wall_minutes, total_model_calls=args.max_calls,
                   max_cost_usd=args.max_cost)
    data["experiment"]["stop_on_success"] = False

    from minecraft_harness.config import validate_config
    validate_config(data)

    args.config.parent.mkdir(parents=True, exist_ok=True)
    args.config.write_text(yaml.safe_dump(data, sort_keys=False, allow_unicode=True))
    write_env(ROOT / "infra" / ".env", api_key=args.api_key, accept_eula=args.accept_eula)
    print(f"wrote {args.config}")
    print(f"wrote {ROOT / 'infra' / '.env'} (mode 600)")
    print(f"agents={args.agents} model={args.model} wall={args.wall_minutes}m calls={args.max_calls} cost=${args.max_cost}")
    if not args.api_key:
        print("WARNING: no DEEPSEEK_API_KEY provided; export it before running", file=sys.stderr)
    if not args.accept_eula:
        print("WARNING: EULA not accepted; start the server only after --accept-eula", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
